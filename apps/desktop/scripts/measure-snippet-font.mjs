// Generates frost's result-snippet character-width table (spec `specs/seo-content.spec.ts`,
// `SNIPPET_FONT`; acceptance `seo-content.feature.md`, Widths). Build-time only: it is never run by
// the app and never packaged. Run it in Electron, not Node (`ELECTRON_RUN_AS_NODE` must be unset):
//
//     env -u ELECTRON_RUN_AS_NODE pnpm --filter @app/desktop exec electron scripts/measure-snippet-font.mjs
//
// It opens one hidden, sandboxed window on `about:blank`, measures every character of the set
// below with canvas `measureText` in the snippet face at the title and description sizes, and
// writes `packages/seo-core/src/content/snippet-font.ts` (advances in 1/100 px). Commit the result.
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { app, BrowserWindow } from 'electron';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..');
const OUT = path.join(ROOT, 'packages/seo-core/src/content/snippet-font.ts');

// Keep equal to `SNIPPET_FONT` (the generated file is checked against it by `snippet-width.test.ts`).
const FAMILY = 'Arial';
// What canvas is asked for: the family first; on Linux fontconfig answers Arial with a
// metric-compatible face (same advances), and the generic family is the last resort.
const FONT_STACK = `${FAMILY}, "Liberation Sans", Helvetica, sans-serif`;
const SIZES = { title: 20, description: 14 };

/** Code point ranges measured: printable ASCII, Latin-1, Latin Extended-A, Greek, Cyrillic, common punctuation and symbols. */
const RANGES = [
  [0x20, 0x7e],
  [0xa0, 0xff],
  [0x100, 0x17f],
  [0x391, 0x3a9],
  [0x3b1, 0x3c9],
  [0x400, 0x45f],
  [0x2010, 0x2027],
  [0x2030, 0x203a],
  [0x20ac, 0x20ac],
  [0x2122, 0x2122],
  [0x2190, 0x2193],
];

const chars = RANGES.flatMap(([from, to]) => Array.from({ length: to - from + 1 }, (_, i) => String.fromCodePoint(from + i))).filter((c) => !/\p{Cn}|\p{Cc}/u.test(c));

app.disableHardwareAcceleration();
app.whenReady().then(async () => {
  const win = new BrowserWindow({
    show: false,
    webPreferences: { sandbox: true, contextIsolation: true, nodeIntegration: false, webSecurity: true, javascript: true },
  });
  try {
    await win.loadURL('about:blank');
    const measured = await win.webContents.executeJavaScript(
      `(() => {
        const ctx = document.createElement('canvas').getContext('2d');
        const chars = ${JSON.stringify(chars)};
        const out = {};
        for (const [kind, size] of Object.entries(${JSON.stringify(SIZES)})) {
          ctx.font = size + 'px ' + ${JSON.stringify(FONT_STACK)};
          out[kind] = chars.map((c) => Math.round(ctx.measureText(c).width * 100));
        }
        return out;
      })()`,
    );
    const lower = [...'abcdefghijklmnopqrstuvwxyz'].map((c) => chars.indexOf(c));
    const average = Object.fromEntries(Object.entries(measured).map(([kind, widths]) => [kind, Math.round(lower.reduce((sum, i) => sum + widths[i], 0) / lower.length)]));
    const source = `// Generated by apps/desktop/scripts/measure-snippet-font.mjs (run in Electron ${process.versions.electron}): do not edit.
// frost's result-snippet character widths (spec \`specs/seo-content.spec.ts\`, \`SNIPPET_FONT\`): each
// character of \`chars\` measured with canvas \`measureText\` in ${JSON.stringify(FONT_STACK)}, at each size.
// \`widths[kind][i]\` is \`chars[i]\`'s advance in 1/100 px; \`averageLower\` the mean of a–z.

export const SNIPPET_FONT_TABLE = {
  family: ${JSON.stringify(FAMILY)},
  fontStack: ${JSON.stringify(FONT_STACK)},
  sizes: ${JSON.stringify(SIZES)},
  chars: ${JSON.stringify(chars.join(''))},
  averageLower: ${JSON.stringify(average)},
  widths: {
${Object.entries(measured)
  .map(([kind, widths]) => `    ${kind}: [${widths.join(', ')}],`)
  .join('\n')}
  },
} as const;
`;
    writeFileSync(OUT, source);
    console.log(`measure-snippet-font: ${chars.length} characters at ${Object.values(SIZES).join(' / ')} px → ${path.relative(ROOT, OUT)}`);
  } finally {
    win.destroy();
    app.quit();
  }
});
